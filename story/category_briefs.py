def creative_brief(category: str) -> str:
    """一类 -> 该类创作卡**全文**(逐条成行)。

    未知类返回空串 —— 调用方(`_story_user`)只在 requested 非空时取,
    而 requested 非空已被 `GenerationBrief.require_valid()` 限定在
    五类里; 这里再兜一层, 绝不为未知类编一段假 Brief。
    """
    lines = CATEGORY_CREATIVE_BRIEFS.get(str(category or "").strip())
    if not lines:
        return ""
    return "\n".join(lines)
